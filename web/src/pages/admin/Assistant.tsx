import { useEffect, useRef, useState } from "react";
import type { FormEvent } from "react";
import { api } from "../../api/client";
import { inp } from "../../components/inputs";
import { Button, Card } from "../../components/ui";

type Msg = { role: "user" | "bot" | "error"; text: string };
const IDEAS = ["How did sales do over the last 7 days?", "Which product sells best?", "How much did we spend on expenses this month?"];

export function Assistant() {
  const [msgs, setMsgs] = useState<Msg[]>([]);
  const [text, setText] = useState("");
  const [busy, setBusy] = useState(false);
  const end = useRef<HTMLDivElement>(null);
  useEffect(() => { end.current?.scrollIntoView({ behavior: "smooth" }); }, [msgs, busy]);

  async function ask(question: string) {
    const q = question.trim();
    if (!q || busy) return;
    setMsgs((m) => [...m, { role: "user", text: q }]);
    setText("");
    setBusy(true);
    try {
      const r = await api.post<{ answer: string }>("/assistant/chat", { question: q });
      setMsgs((m) => [...m, { role: "bot", text: r.answer }]);
    } catch (e) {
      setMsgs((m) => [...m, { role: "error", text: `The assistant is unavailable: ${e instanceof Error ? e.message : "unknown error"}` }]);
    } finally {
      setBusy(false);
    }
  }
  const submit = (e: FormEvent) => { e.preventDefault(); ask(text); };

  return (
    <div className="flex h-[calc(100vh-9rem)] min-h-[28rem] flex-col gap-4">
      <div><h1 className="text-3xl font-bold">Assistant</h1><p className="text-sm text-muted">Ask about sales, stock and expenses. Answers are generated by the backend assistant from your data.</p></div>
      <Card className="flex-1 space-y-3 overflow-y-auto p-4" aria-live="polite">
        {msgs.length === 0 && (
          <div className="space-y-3">
            <p className="text-muted">Try one of these, or type your own question.</p>
            <div className="flex flex-wrap gap-2">{IDEAS.map((i) => <button key={i} onClick={() => ask(i)} className="rounded-full border border-line bg-white px-4 py-1.5 text-sm hover:bg-saffron-soft">{i}</button>)}</div>
          </div>
        )}
        {msgs.map((m, i) => (
          <div key={i} className={`flex ${m.role === "user" ? "justify-end" : "justify-start"}`}>
            <p className={`max-w-[85%] whitespace-pre-wrap rounded-2xl px-4 py-2.5 text-sm ${m.role === "user" ? "bg-terracotta text-white" : m.role === "error" ? "bg-bad/10 text-bad" : "bg-saffron-soft text-ink"}`}>{m.text}</p>
          </div>
        ))}
        {busy && <p className="text-sm text-muted">Thinking...</p>}
        <div ref={end} />
      </Card>
      <form onSubmit={submit} className="flex gap-3">
        <input className={inp} value={text} maxLength={500} placeholder="Ask a question" aria-label="Question" onChange={(e) => setText(e.target.value)} />
        <Button type="submit" disabled={busy || !text.trim()}>Send</Button>
      </form>
    </div>
  );
}